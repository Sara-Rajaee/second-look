# configs/derive_paths.sh
# Reads paths.env, computes all derived paths, exports everything, and (once
# the one-time install below succeeds) writes a plain `export VAR=value`
# artifact to configs/.node_envs/<node_name>/load_env.sh.
#
# Run this once per node (e.g. from a login/dev node, or any node where it's
# fine to wait on `uv sync`). For every subsequent shell/job, prefer
# `source configs/load_env.sh`, which just loads the artifact instead of
# redoing any of this.
#
# Sourced (not executed) so exports stick. Everything below runs inside a
# function with `local -`, so `set -euo pipefail` is scoped to this script's
# own execution: a failing command aborts derive_paths_main via a plain
# `return`, which does NOT kill the shell that sourced us. Without this,
# `set -e` leaking into an interactive shell means ANY later failing command
# in that same shell can terminate the shell outright and drop your
# connection to the node.

derive_paths_main() {
  local -
  set -euo pipefail

  local paths_file="${PATHS_FILE:-configs/local/paths.env}"
  if [[ ! -f "$paths_file" ]]; then
    echo "ERROR: $paths_file not found." >&2
    echo "Run: cp configs/local/paths.env.example configs/local/paths.env" >&2
    echo "     then edit SHARED to point at fast local/node storage." >&2
    return 1
  fi

  # Load user inputs.
  set -a
  source "$paths_file"
  set +a

  : "${SHARED:?SHARED must be set in $paths_file}"
  export PYTHON="${PYTHON:-python}"

  echo "Using SHARED=$SHARED"
  mkdir -p "$SHARED"

  # ---------- derived paths ----------
  # uv's own download/build cache is only needed transiently during `uv sync`
  # -- put it on node-local /tmp rather than SHARED, which may itself be
  # quota-limited depending on which storage backs it.
  export UV_CACHE_DIR="/tmp/$USER/uv_cache"

  export CACHE_BASE="$SHARED/cache"
  export HF_HOME="$CACHE_BASE/hf_cache"
  export TORCH_HOME="$HF_HOME/torch"
  export XDG_CACHE_HOME="$HF_HOME/xdg"

  # ---------- create dirs (idempotent) ----------
  mkdir -p "$UV_CACHE_DIR" "$HF_HOME" "$TORCH_HOME" "$XDG_CACHE_HOME"

  # ---------- one-time install: .venv into SHARED ----------
  # Gated by $SHARED/COMPLETED so re-sourcing this file (every new shell/job)
  # is just a marker check, not a re-sync, once the first install succeeds.
  local completed_marker="$SHARED/COMPLETED"
  local install_lock_dir="$SHARED/.locks"
  local install_lock_path="$install_lock_dir/install.lock"

  local repo_root
  repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

  # Node-local venv: point uv straight at $SHARED/.venv instead of symlinking
  # it into the (NFS-shared) repo root. Repo root is the same physical path
  # on every node, so a symlink there would race across nodes running this
  # concurrently with different $SHARED.
  export UV_PROJECT_ENVIRONMENT="$SHARED/.venv"
  mkdir -p "$SHARED/.venv"

  if [[ ! -f "$completed_marker" ]]; then
    mkdir -p "$install_lock_dir"
    while ! mkdir "$install_lock_path" 2>/dev/null; do
      if [[ -f "$completed_marker" ]]; then
        break
      fi
      echo "Waiting for another process to finish installing into $SHARED" >&2
      echo "You can clean the lock with: rm -rf $install_lock_path" >&2
      sleep 1
    done

    if [[ ! -f "$completed_marker" ]]; then
      cleanup_install_lock() {
        rmdir "$install_lock_path" 2>/dev/null || true
      }
      trap cleanup_install_lock RETURN

      echo "Installing .venv into $SHARED/.venv ..." >&2
      uv sync --project "$repo_root"

      touch "$completed_marker"
      echo "Finished installing into $SHARED" >&2
    fi
  else
    echo "Using existing installation at $SHARED (found COMPLETED marker)" >&2
  fi

  # ---------- env artifact ----------
  # Plain `export VAR=value` lines, safe and fast to `source` from any shell
  # (see configs/load_env.sh). Keyed by node name -- not $SHARED -- because
  # $SHARED itself can differ per node and UV_CACHE_DIR is always
  # node-local /tmp anyway. Regenerated on every successful run so it always
  # reflects the exports above.
  local node_dir="configs/.node_envs/$(hostname -s)"
  mkdir -p "$node_dir"
  local env_artifact="$node_dir/load_env.sh"
  {
    echo "# Auto-generated by configs/derive_paths.sh on $(date -u +%FT%TZ)."
    echo "# Do not edit by hand -- re-run 'source configs/derive_paths.sh' to regenerate."
    local var
    for var in SHARED PYTHON UV_PROJECT_ENVIRONMENT UV_CACHE_DIR \
      CACHE_BASE HF_HOME TORCH_HOME XDG_CACHE_HOME; do
      printf 'export %s=%q\n' "$var" "${!var}"
    done
  } >"$env_artifact"
  echo "Wrote env artifact to $env_artifact (use configs/load_env.sh to load it quickly next time)" >&2
}

if ! derive_paths_main; then
  unset -f derive_paths_main
  return 1 2>/dev/null || exit 1
fi
unset -f derive_paths_main
